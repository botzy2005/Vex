import { invoke } from '@tauri-apps/api/core';
import { listen } from '@tauri-apps/api/event';
import type { Backend } from './backend';
import type { WidgetDef } from '../shared/types';
import widgets from '../shared/widgets.json';

export function createTauriBackend(): Backend {
  const sub = <T,>(event: string, cb: (payload: T) => void) => listen<T>(event, (e) => cb(e.payload));
  return {
    kind: 'tauri',
    getSettings: () => invoke('get_settings'),
    updateSettings: (patch) => invoke('update_settings', { patch }),
    onSettingsChanged: (cb) => sub('settings-changed', cb),
    listMonitors: () => invoke('list_monitors'),
    setIslandSize: (width, height) => invoke('set_island_size', { width, height }),
    setIslandOffset: (offsetX, commit) => invoke('set_island_offset', { offsetX, commit }),
    setIslandHidden: (hidden) => invoke('set_island_hidden', { hidden }),
    onIslandReveal: (cb) => sub<null>('island-reveal', () => cb()),
    openSettings: () => invoke('open_settings'),
    quit: () => invoke('quit_app'),
    onIslandToggle: (cb) => sub<null>('island-toggle', () => cb()),
    getMedia: () => invoke('media_get_state'),
    onMedia: (cb) => sub('media-state', cb),
    mediaTransport: (command) => invoke('media_transport', { command }),
    lyricsFetch: (track) => invoke('lyrics_fetch', { track }),
    aiSend: ({ conversationId, text, context }) => invoke('ai_send', { conversationId, text, context }),
    aiCancel: () => invoke('ai_cancel'),
    onAiEvent: (cb) => sub('ai-event', cb),
    aiKeyStatus: (provider) => invoke('ai_key_status', { provider }),
    aiSetKey: (provider, key) => invoke('ai_set_key', { provider, key }),
    aiClearKey: (provider) => invoke('ai_clear_key', { provider }),
    aiListModels: (provider) => invoke('ai_list_models', { provider }),
    aiTest: (provider) => invoke('ai_test', { provider }),
    aiMetrics: () => invoke('ai_metrics'),
    aiMetricsClear: () => invoke('ai_metrics_clear'),
    aiPreload: (model) => invoke('ai_preload', { model }),
    aiBenchmark: (models, includeThinking) => invoke('ai_benchmark', { models, includeThinking }),
    onBenchRow: (cb) => sub('ai-bench-row', cb),
    chatList: () => invoke('chat_list'),
    chatGet: (id) => invoke('chat_get', { id }),
    chatDelete: (id) => invoke('chat_delete', { id }),
    chatClearAll: () => invoke('chat_clear_all'),
    getNotifications: () => invoke('notifications_get'),
    onNotifications: (cb) => sub('notifications-view', cb),
    notificationDismiss: (id) => invoke('notification_dismiss', { id }),
    notificationDismissAll: () => invoke('notification_dismiss_all'),
    notificationClear: (id) => invoke('notification_clear', { id }),
    notificationClearAll: () => invoke('notification_clear_all'),
    notificationOpen: (id) => invoke('notification_open', { id }),
    clipboardStatus: () => invoke('clipboard_status'),
    onClipboard: (cb) => sub('clipboard-changed', cb),
    clipboardList: (query) => invoke('clipboard_list', { query }),
    clipboardCopy: (id) => invoke('clipboard_copy', { id }),
    clipboardPin: (id, pinned) => invoke('clipboard_pin', { id, pinned }),
    clipboardDelete: (id) => invoke('clipboard_delete', { id }),
    clipboardClear: (keepPinned) => invoke('clipboard_clear', { keepPinned }),
    screenshotCapture: (mode) => invoke('screenshot_capture', { mode }),
    screenshotRegionSelect: (monitor, x0, y0, x1, y1) => invoke('screenshot_region_select', { monitor, x0, y0, x1, y1 }),
    screenshotRegionCancel: () => invoke('screenshot_region_cancel'),
    screenshotList: () => invoke('screenshot_list'),
    screenshotImage: (id) => invoke('screenshot_image', { id }),
    screenshotDelete: (id) => invoke('screenshot_delete', { id }),
    screenshotClear: () => invoke('screenshot_clear'),
    screenshotCopy: (source) => invoke('screenshot_copy', { source }),
    screenshotSave: (source, ask) => invoke('screenshot_save', { source, ask }),
    screenshotPickFolder: () => invoke('screenshot_pick_folder'),
    screenshotReveal: (path) => invoke('screenshot_reveal', { path }),
    screenshotOpenEditor: (id) => invoke('screenshot_open_editor', { id }),
    onScreenshotCaptured: (cb) => sub('screenshot-captured', cb),
    onScreenshotError: (cb) => sub('screenshot-error', cb),
    onEditorLoad: (cb) => sub('editor-load', cb),
    assistantPreview: (state) => invoke('assistant_preview_state', { state }),
    onAssistantState: (cb) => sub('assistant-state', cb),
    launcherSearch: (query) => invoke('launcher_search', { query }),
    launcherRun: (input, target, reveal) => invoke('launcher_run', { input, target, reveal: reveal ?? false }),
    launcherHide: () => invoke('launcher_hide'),
    launcherState: () => invoke('launcher_state'),
    launcherSetPin: (id, pinned) => invoke('launcher_set_pin', { id, pinned }),
    launcherRecordSearch: (text) => invoke('launcher_record_search', { text }),
    launcherClearHistory: () => invoke('launcher_clear_history'),
    launcherRefresh: () => invoke('launcher_refresh'),
    launcherAppIcon: (id) => invoke('launcher_app_icon', { id }),
    launcherAiInfo: () => invoke('launcher_ai_info'),
    launcherAiSend: (kind, text, language) => invoke('launcher_ai_send', { kind, text, language }),
    onLauncherAi: (cb) => sub('launcher-ai-event', cb),
    onLauncherOpen: (cb) => sub<null>('launcher-open', () => cb()),
    onLauncherClose: (cb) => sub<null>('launcher-close', () => cb()),
    onLauncherIndex: (cb) => sub<null>('launcher-index', () => cb()),
    hubOpen: (widget) => invoke('hub_open', { widget: widget ?? null }),
    hubCatalog: async () => widgets.widgets as WidgetDef[],
    hubLayout: () => invoke('hub_layout'),
    hubSaveLayout: (layout) => invoke('hub_save_layout', { layout }),
    onHubChanged: (cb) => sub('hub-changed', cb),
    onHubFocus: (cb) => sub('hub-focus', cb),
    hubDataGet: (kind) => invoke('hub_data_get', { kind }),
    hubDataSet: (kind, value) => invoke('hub_data_set', { kind, value }),
    hubSetStatus: (kind, status) => invoke('hub_set_status', { kind, status }),
    hubStatuses: () => invoke('hub_statuses'),
    onHubStatus: (cb) => sub('hub-status', cb),
    timersList: () => invoke('timers_list'),
    timerCreate: (owner, label, durationMs) => invoke('timer_create', { owner, label, durationMs }),
    timerStart: (id) => invoke('timer_start', { id }),
    timerPause: (id) => invoke('timer_pause', { id }),
    timerReset: (id) => invoke('timer_reset', { id }),
    timerDelete: (id) => invoke('timer_delete', { id }),
    timerSetDuration: (id, durationMs) => invoke('timer_set_duration', { id, durationMs }),
    timerSetLabel: (id, label) => invoke('timer_set_label', { id, label }),
    onTimers: (cb) => sub('timers-changed', cb),
    onTimerFinished: (cb) => sub('timer-finished', cb),
  };
}
